import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(
    readFileSync(
        new URL("../out/ExamRegistry.sol/ExamRegistry.json", import.meta.url),
        "utf8",
    ),
);
const out = `// Generated by packages/contracts/script/export-abi.ts from the forge artifact. Do not edit.
export const examRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const examRegistryBytecode = "${artifact.bytecode.object}" as const;
`;
writeFileSync(new URL("../../protocol/src/abi.ts", import.meta.url), out);
console.log(
    `abi: ${artifact.abi.length} entries, bytecode: ${(artifact.bytecode.object.length - 2) / 2} bytes`,
);
