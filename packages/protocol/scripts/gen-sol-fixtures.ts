import { writeFileSync } from "node:fs";
import { bls12_381 } from "@noble/curves/bls12-381.js";
import { concatBytes, fromHex, toHex } from "../src/bytes.ts";
import {
    DevBeacon,
    DST_G1,
    QUICKNET,
    publicKeyToEip2537,
    roundMessage,
    signatureToEip2537,
} from "../src/drand.ts";

const fp = (v: bigint) => {
    const o = new Uint8Array(64);
    o.set(fromHex(v.toString(16).padStart(96, "0")), 16);
    return o;
};
const g = bls12_381.G2.Point.BASE.negate().toAffine();
const h = bls12_381.shortSignatures
    .hash(roundMessage(1_000_000), DST_G1)
    .toAffine();
const dev = new DevBeacon(fromHex("0x" + "11".repeat(32)), 1_700_000_000, 1);

const consts: Record<string, string> = {
    NEG_G2: toHex(concatBytes(fp(g.x.c0), fp(g.x.c1), fp(g.y.c0), fp(g.y.c1))),
    QN_PK: publicKeyToEip2537(QUICKNET.public_key),
    QN_PK_COMPRESSED: `0x${QUICKNET.public_key}`,
    QN_SIG_1000000: signatureToEip2537(
        "83ad29e4c409f9470fc2ef02f90214df49e02b441a1a241a82d622d9f608ef98fd8b11a029f1bee9d9e83b45088abe72",
    ),
    QN_SIG_1000001: signatureToEip2537(
        "a5bd91e5e2d8c0bf51bffdfad87eef34348fd9c0b2df2bee39db90bdef7e1399b1a77bb2fe98b24d84c0936a306c4218",
    ),
    QN_H_1000000: toHex(concatBytes(fp(h.x), fp(h.y))),
    DEV_PK: publicKeyToEip2537(dev.info.public_key),
    DEV_PK_COMPRESSED: `0x${dev.info.public_key}`,
};
for (const r of [5, 10, 20, 30, 40, 50, 60])
    consts[`DEV_SIG_${r}`] = signatureToEip2537(dev.sign(r).signature);

const body = Object.entries(consts)
    .map(([k, v]) => `    bytes internal constant ${k} = hex"${v.slice(2)}";`)
    .join("\n");
const out = `// SPDX-License-Identifier: MIT
// Generated by packages/protocol/scripts/gen-sol-fixtures.ts. Do not edit.
pragma solidity ^0.8.28;

library Fixtures {
${body}
}
`;
writeFileSync(
    new URL("../../contracts/test/Fixtures.sol", import.meta.url),
    out,
);
console.log(
    `wrote ${Object.keys(consts).length} fixtures; NEG_G2=${consts.NEG_G2!.slice(0, 18)}...`,
);
